/// Textos de la app en español, inglés y quechua (chanka, provisional).
///
/// Reglas:
/// - Cada clave existe en `_es` (fuente de verdad).
/// - `en` y `qu` caen a `es` si falta la clave.
/// - Variables con `{nombre}`: `tr(lang, 'clave', {'nombre': valor})`.
library;

enum AppLang { es, en, qu }

extension AppLangInfo on AppLang {
  String get code => name;

  /// Nombre del idioma en su propia lengua (para el selector).
  String get nativeName => switch (this) {
    AppLang.es => 'Español',
    AppLang.en => 'English',
    AppLang.qu => 'Runasimi',
  };

  /// Idioma que se pide al backend para las explicaciones (solo es/en).
  String get apiLang => this == AppLang.en ? 'en' : 'es';

  static AppLang fromCode(String? code) {
    switch (code) {
      case 'en':
        return AppLang.en;
      case 'qu':
        return AppLang.qu;
      default:
        return AppLang.es;
    }
  }
}

String tr(AppLang lang, String key, [Map<String, Object?> args = const {}]) {
  final table = switch (lang) {
    AppLang.es => _es,
    AppLang.en => _en,
    AppLang.qu => _qu,
  };
  var text = table[key] ?? _es[key] ?? key;
  args.forEach((name, value) {
    text = text.replaceAll('{$name}', '${value ?? ''}');
  });
  return text;
}

